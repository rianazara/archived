#!/usr/bin/env python3
"""Regenerate INDEX.md from frontmatter across entries/**/*.md."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "entries"
INDEX = ROOT / "INDEX.md"

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n", re.DOTALL)


def parse_frontmatter(text: str) -> dict:
    match = FRONTMATTER_RE.match(text)
    if not match:
        return {}
    fields = {}
    for line in match.group(1).splitlines():
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields


def collect_entries() -> dict[str, list[tuple[str, dict]]]:
    by_topic: dict[str, list[tuple[str, dict]]] = {}
    if not ENTRIES.exists():
        return by_topic
    for path in sorted(ENTRIES.rglob("*.md")):
        fields = parse_frontmatter(path.read_text())
        topic = fields.get("topic", path.parent.name)
        rel = path.relative_to(ROOT)
        by_topic.setdefault(topic, []).append((str(rel), fields))
    return by_topic


def render(by_topic: dict[str, list[tuple[str, dict]]]) -> str:
    lines = ["# Index", "", "Auto-generated by `scripts/rebuild_index.py`. Do not edit by hand.", ""]
    if not by_topic:
        lines.append("_No entries yet. Run `Store this: …` in a Claude Code session to add one._")
        return "\n".join(lines) + "\n"

    for topic in sorted(by_topic):
        lines.append(f"## {topic}")
        lines.append("")
        for rel, fields in sorted(by_topic[topic]):
            title = fields.get("title", Path(rel).stem)
            updated = fields.get("updated", fields.get("created", ""))
            tags = fields.get("tags", "")
            suffix = f" — updated {updated}" if updated else ""
            tag_suffix = f" ({tags})" if tags else ""
            lines.append(f"- [{title}]({rel}){tag_suffix}{suffix}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    by_topic = collect_entries()
    INDEX.write_text(render(by_topic))
    total = sum(len(v) for v in by_topic.values())
    print(f"Indexed {total} entr{'y' if total == 1 else 'ies'} across {len(by_topic)} topic(s).")


if __name__ == "__main__":
    main()
